// Only explicitly listed PUBLIC_* values may enter the browser bundle.
const fs = require("node:fs");
const path = require("node:path");
const { parseEnv } = require("node:util");

function loadEnvironment(root, overrides = process.env) {
  const values = {};
  for (const name of [".env", ".env.local"]) {
    const file = path.join(root, name);
    if (fs.existsSync(file))
      Object.assign(values, parseEnv(fs.readFileSync(file, "utf8")));
  }
  return { ...values, ...overrides };
}

function publicConfiguration(env) {
  if (env.ZETHO_REQUIRE_PUBLIC_CONFIG === "1") {
    const required = [
      "PUBLIC_APP_URL",
      "PUBLIC_API_URL",
      "PUBLIC_APPWRITE_ENDPOINT",
      "PUBLIC_APPWRITE_PROJECT",
    ];
    const missing = required.filter((name) => !env[name]?.trim());
    if (missing.length) {
      throw new Error(`Missing deployment configuration: ${missing.join(", ")}`);
    }
  }
  function url(name, fallback) {
    const value = env[name] || fallback;
    const parsed = new URL(value);
    if (
      !["http:", "https:"].includes(parsed.protocol) ||
      parsed.username ||
      parsed.password
    ) {
      throw new Error(`${name} must be an HTTP(S) URL without credentials`);
    }
    return value;
  }
  return {
    appUrl: url("PUBLIC_APP_URL", "http://localhost:4200/"),
    appwriteEndpoint: url("PUBLIC_APPWRITE_ENDPOINT", "http://localhost/v1"),
    appwriteProject: env.PUBLIC_APPWRITE_PROJECT || "zetho-local",
    themesBucketId: env.PUBLIC_THEMES_BUCKET_ID || "zetho-themes",
    zethoApiEndpoint: url("PUBLIC_API_URL", "http://localhost:3000/"),
    firebase: {
      apiKey: env.PUBLIC_FIREBASE_API_KEY || "",
      authDomain: env.PUBLIC_FIREBASE_AUTH_DOMAIN || "",
      projectId: env.PUBLIC_FIREBASE_PROJECT_ID || "",
      storageBucket: env.PUBLIC_FIREBASE_STORAGE_BUCKET || "",
      messagingSenderId: env.PUBLIC_FIREBASE_MESSAGING_SENDER_ID || "",
      appId: env.PUBLIC_FIREBASE_APP_ID || "",
      measurementId: env.PUBLIC_FIREBASE_MEASUREMENT_ID || "",
    },
  };
}

if (require.main === module) {
  const root = path.resolve(__dirname, "..");
  const config = publicConfiguration(loadEnvironment(root));
  fs.writeFileSync(
    path.join(root, "src/environments/environment.generated.ts"),
    "// Generated by pnpm configure. Do not edit or commit.\n" +
      `export const publicEnvironment = ${JSON.stringify(config, null, 2)};\n`,
  );
  console.log("Public frontend configuration generated.");
}

module.exports = { loadEnvironment, publicConfiguration };
